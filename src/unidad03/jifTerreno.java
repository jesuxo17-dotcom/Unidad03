    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        // se toman los datos de los text fields y se convierte a valor numerico
        terreno.setNumLote(Integer.parseInt(this.txtNumTerreno.getText()));
        terreno.setLargo(Float.parseFloat(this.txtLargo.getText()));
        terreno.setAncho(Float.parseFloat(this.txtAncho.getText()));

        // Listo se mostrara un mensaje
        JOptionPane.showMessageDialog(this, "Se Guardó el objeto Terreno con exito");
        this.limpiar();
        this.btnMostrar.setEnabled(true); // se activa el boton para poderlo consultar.
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
        // codificar mostrar
        this.txtNumTerreno.setText(String.valueOf(terreno.getNumLote()));
        this.txtAncho.setText(String.valueOf(terreno.getAncho()));
        this.txtLargo.setText(String.valueOf(terreno.getLargo()));

        this.txtPerimetro.setText(String.valueOf(terreno.calcularPerimetro()));
        this.txtArea.setText(String.valueOf(terreno.calcularArea()));
        // listo.
    }//GEN-LAST:event_btnMostrarActionPerformed


